-- ---------- Tables ----------

-- Emplacements (une armoire, un étage, un tiroir…). L'id sert dans le QR code.
create table if not exists labo_lieux (
  id      text primary key,
  salle   text not null,
  nom     text not null,
  details text,
  ordre   int not null default 0
);

-- Tout ce qu'il y a au labo : produits, verrerie, matériel, consommables.
create table if not exists labo_articles (
  id              bigint generated by default as identity primary key,
  domaine         text not null default 'chimie'
                  check (domaine in ('chimie','biologie','physique','commun')),
  categorie       text not null default 'produit'
                  check (categorie in ('produit','verrerie','materiel','consommable')),
  nom             text not null,
  formule         text,
  conditionnement text,                 -- « 500 g », « 1 L à 1 mol/L »…
  suivi           text not null default 'etat'
                  check (suivi in ('etat','nombre')),
  quantite        int,                  -- seulement si suivi = 'nombre'
  cible           int,                  -- quantité « normale » à avoir
  seuil           int,                  -- en dessous : à racheter
  etat            text not null default 'ok'
                  check (etat in ('ok','presque_vide','vide','introuvable')),
  lieu_id         text references labo_lieux(id) on update cascade on delete set null,
  precision_lieu  text,                 -- « 2e étage », « planche 3 »…
  fournisseur     text,
  lien            text,
  prix            numeric(10,2),        -- prix d'un conditionnement / d'une pièce
  remarque        text,
  a_verifier      boolean not null default false,
  commande_le     date,                 -- non vide = commandé, en attente
  actif           boolean not null default true,
  maj_le          timestamptz not null default now(),
  maj_par         text
);

-- Journal de tout ce qui se passe (qui a signalé quoi, achats reçus…).
create table if not exists labo_evenements (
  id         bigint generated by default as identity primary key,
  article_id bigint references labo_articles(id) on delete cascade,
  type       text not null,
  quantite   int,
  par        text,
  note       text,
  cree_le    timestamptz not null default now()
);

-- Nouveaux achats : ce qui n'existe pas encore au labo.
create table if not exists labo_demandes (
  id          bigint generated by default as identity primary key,
  nom         text not null,
  domaine     text not null default 'chimie'
              check (domaine in ('chimie','biologie','physique','commun')),
  categorie   text not null default 'materiel'
              check (categorie in ('produit','verrerie','materiel','consommable')),
  quantite    int not null default 1,
  prix        numeric(10,2),            -- prix unitaire estimé
  fournisseur text,
  lien        text,
  pour        text,                     -- cours / labo concerné
  statut      text not null default 'a_commander'
              check (statut in ('a_commander','commande','recu','abandonne')),
  par         text,
  cree_le     timestamptz not null default now(),
  commande_le date,
  recu_le     date,
  article_id  bigint references labo_articles(id) on delete set null
);

-- Codes d'accès (illisibles depuis l'app : aucune règle de lecture).
create table if not exists labo_config (
  cle    text primary key,
  valeur text not null
);

create index if not exists labo_evenements_article on labo_evenements(article_id, cree_le desc);

-- ---------- Droits ----------
-- La clé publique de l'app peut LIRE, jamais écrire directement.
-- Toute écriture passe par les fonctions ci-dessous, qui vérifient le code.

alter table labo_lieux      enable row level security;
alter table labo_articles   enable row level security;
alter table labo_evenements enable row level security;
alter table labo_demandes   enable row level security;
alter table labo_config     enable row level security;

drop policy if exists lecture on labo_lieux;
drop policy if exists lecture on labo_articles;
drop policy if exists lecture on labo_evenements;
drop policy if exists lecture on labo_demandes;
create policy lecture on labo_lieux      for select to anon using (true);
create policy lecture on labo_articles   for select to anon using (true);
create policy lecture on labo_evenements for select to anon using (true);
create policy lecture on labo_demandes   for select to anon using (true);

-- ---------- Actions ----------

-- Renvoie 'admin', 'prof' ou null.
create or replace function labo_role(p_code text) returns text
language sql stable security definer set search_path = public as $$
  select case
    when p_code = (select valeur from labo_config where cle = 'code_admin') then 'admin'
    when p_code = (select valeur from labo_config where cle = 'code_prof')  then 'prof'
  end;
$$;

create or replace function labo_exiger(p_code text, p_admin boolean default false) returns void
language plpgsql stable security definer set search_path = public as $$
declare r text := labo_role(p_code);
begin
  if r is null then raise exception 'Code incorrect'; end if;
  if p_admin and r <> 'admin' then raise exception 'Réservé au code administrateur'; end if;
end $$;

-- Signalement depuis le labo.
--   p_type : ok | presque_vide | vide | introuvable | casse | comptage
--   casse    : retire p_quantite pièces (1 par défaut)
--   comptage : fixe la quantité réelle (tournée d'inventaire) et retire « à vérifier »
create or replace function labo_signaler(p_code text, p_article bigint, p_type text,
                                         p_quantite int default null, p_par text default null,
                                         p_note text default null)
returns labo_articles
language plpgsql security definer set search_path = public as $$
declare a labo_articles;
begin
  perform labo_exiger(p_code);
  select * into a from labo_articles where id = p_article for update;
  if not found then raise exception 'Article inconnu'; end if;

  if p_type in ('ok','presque_vide','vide','introuvable') then
    update labo_articles set etat = p_type where id = p_article;
  elsif p_type = 'casse' then
    update labo_articles
       set quantite = greatest(coalesce(quantite,0) - coalesce(p_quantite,1), 0)
     where id = p_article;
  elsif p_type = 'comptage' then
    update labo_articles
       set quantite = coalesce(p_quantite, quantite),
           etat = case when etat = 'introuvable' then 'ok' else etat end,
           a_verifier = false
     where id = p_article;
  else
    raise exception 'Type de signalement inconnu : %', p_type;
  end if;

  update labo_articles set maj_le = now(), maj_par = p_par where id = p_article;
  insert into labo_evenements(article_id, type, quantite, par, note)
       values (p_article, p_type, p_quantite, p_par, p_note);
  select * into a from labo_articles where id = p_article;
  return a;
end $$;

-- Commande d'un article à renouveler.
--   p_action : commande | annule | recu
--   recu : remet l'état à OK, ajoute p_quantite au stock compté, met à jour prix/fournisseur
create or replace function labo_commande(p_code text, p_article bigint, p_action text,
                                         p_quantite int default null, p_prix numeric default null,
                                         p_fournisseur text default null, p_par text default null)
returns labo_articles
language plpgsql security definer set search_path = public as $$
declare a labo_articles;
begin
  -- Commander, annuler, réceptionner : tous les profs.
  perform labo_exiger(p_code);
  if p_action = 'commande' then
    update labo_articles set commande_le = current_date where id = p_article;
  elsif p_action = 'annule' then
    update labo_articles set commande_le = null where id = p_article;
  elsif p_action = 'recu' then
    update labo_articles
       set commande_le = null,
           etat = 'ok',
           quantite = case when suivi = 'nombre'
                           then coalesce(quantite,0) + coalesce(p_quantite,0) else quantite end,
           prix = coalesce(p_prix, prix),
           fournisseur = coalesce(nullif(p_fournisseur,''), fournisseur)
     where id = p_article;
  else
    raise exception 'Action inconnue : %', p_action;
  end if;
  update labo_articles set maj_le = now(), maj_par = p_par where id = p_article;
  insert into labo_evenements(article_id, type, quantite, par, note)
       values (p_article, p_action, p_quantite, p_par,
               case when p_action = 'recu' and p_fournisseur is not null then p_fournisseur end);
  select * into a from labo_articles where id = p_article;
  return a;
end $$;

-- Créer (p_id null) ou modifier un article. Champs passés en JSON.
-- Ouvert à tous : ajouter un achat reçu ou corriger un emplacement doit rester simple.
create or replace function labo_article_enregistrer(p_code text, p_id bigint, p_data jsonb,
                                                    p_par text default null)
returns labo_articles
language plpgsql security definer set search_path = public as $$
declare a labo_articles; nouvel_id bigint;
begin
  perform labo_exiger(p_code);
  if p_id is null then
    insert into labo_articles(domaine, categorie, nom, formule, conditionnement, suivi,
                              quantite, cible, seuil, etat, lieu_id, precision_lieu,
                              fournisseur, lien, prix, remarque, maj_par)
    values (coalesce(p_data->>'domaine','chimie'), coalesce(p_data->>'categorie','produit'),
            p_data->>'nom', p_data->>'formule', p_data->>'conditionnement',
            coalesce(p_data->>'suivi','etat'),
            (p_data->>'quantite')::int, (p_data->>'cible')::int, (p_data->>'seuil')::int,
            coalesce(p_data->>'etat','ok'), nullif(p_data->>'lieu_id',''), p_data->>'precision_lieu',
            p_data->>'fournisseur', p_data->>'lien', (p_data->>'prix')::numeric,
            p_data->>'remarque', p_par)
    returning id into nouvel_id;
    insert into labo_evenements(article_id, type, par, note)
         values (nouvel_id, 'creation', p_par, p_data->>'note');
  else
    nouvel_id := p_id;
    update labo_articles set
      domaine         = coalesce(p_data->>'domaine', domaine),
      categorie       = coalesce(p_data->>'categorie', categorie),
      nom             = coalesce(p_data->>'nom', nom),
      formule         = case when p_data ? 'formule' then p_data->>'formule' else formule end,
      conditionnement = case when p_data ? 'conditionnement' then p_data->>'conditionnement' else conditionnement end,
      suivi           = coalesce(p_data->>'suivi', suivi),
      quantite        = case when p_data ? 'quantite' then (p_data->>'quantite')::int else quantite end,
      cible           = case when p_data ? 'cible' then (p_data->>'cible')::int else cible end,
      seuil           = case when p_data ? 'seuil' then (p_data->>'seuil')::int else seuil end,
      lieu_id         = case when p_data ? 'lieu_id' then nullif(p_data->>'lieu_id','') else lieu_id end,
      precision_lieu  = case when p_data ? 'precision_lieu' then p_data->>'precision_lieu' else precision_lieu end,
      fournisseur     = case when p_data ? 'fournisseur' then p_data->>'fournisseur' else fournisseur end,
      lien            = case when p_data ? 'lien' then p_data->>'lien' else lien end,
      prix            = case when p_data ? 'prix' then (p_data->>'prix')::numeric else prix end,
      remarque        = case when p_data ? 'remarque' then p_data->>'remarque' else remarque end,
      a_verifier      = coalesce((p_data->>'a_verifier')::boolean, a_verifier),
      maj_le = now(), maj_par = p_par
    where id = p_id;
    insert into labo_evenements(article_id, type, par) values (p_id, 'modification', p_par);
  end if;
  select * into a from labo_articles where id = nouvel_id;
  return a;
end $$;

-- Retirer un article de l'inventaire (réservé à l'administratrice). Rien n'est effacé.
create or replace function labo_article_retirer(p_code text, p_id bigint, p_par text default null)
returns void
language plpgsql security definer set search_path = public as $$
begin
  perform labo_exiger(p_code, true);
  update labo_articles set actif = false, maj_le = now(), maj_par = p_par where id = p_id;
  insert into labo_evenements(article_id, type, par) values (p_id, 'retrait', p_par);
end $$;

-- Nouveaux achats (ce qui n'existe pas encore au labo).
--   p_action : creer | modifier | commande | recu | abandonne | rouvrir
create or replace function labo_demande(p_code text, p_action text, p_id bigint default null,
                                        p_data jsonb default '{}'::jsonb, p_par text default null)
returns labo_demandes
language plpgsql security definer set search_path = public as $$
declare d labo_demandes; nouvel_id bigint := p_id;
begin
  -- Proposer, commander et réceptionner : tous les profs. Le reste : administratrice.
  perform labo_exiger(p_code, p_action not in ('creer','commande','recu'));
  if p_action = 'creer' then
    insert into labo_demandes(nom, domaine, categorie, quantite, prix, fournisseur, lien, pour, par)
    values (p_data->>'nom', coalesce(p_data->>'domaine','chimie'),
            coalesce(p_data->>'categorie','materiel'), coalesce((p_data->>'quantite')::int,1),
            (p_data->>'prix')::numeric, p_data->>'fournisseur', p_data->>'lien',
            p_data->>'pour', p_par)
    returning id into nouvel_id;
  elsif p_action = 'modifier' then
    update labo_demandes set
      nom = coalesce(p_data->>'nom', nom),
      domaine = coalesce(p_data->>'domaine', domaine),
      categorie = coalesce(p_data->>'categorie', categorie),
      quantite = coalesce((p_data->>'quantite')::int, quantite),
      prix = case when p_data ? 'prix' then (p_data->>'prix')::numeric else prix end,
      fournisseur = case when p_data ? 'fournisseur' then p_data->>'fournisseur' else fournisseur end,
      lien = case when p_data ? 'lien' then p_data->>'lien' else lien end,
      pour = case when p_data ? 'pour' then p_data->>'pour' else pour end
    where id = p_id;
  elsif p_action = 'commande' then
    update labo_demandes set statut = 'commande', commande_le = current_date where id = p_id;
  elsif p_action = 'recu' then
    update labo_demandes set statut = 'recu', recu_le = current_date,
           article_id = coalesce((p_data->>'article_id')::bigint, article_id)
     where id = p_id;
  elsif p_action = 'abandonne' then
    update labo_demandes set statut = 'abandonne' where id = p_id;
  elsif p_action = 'rouvrir' then
    update labo_demandes set statut = 'a_commander', commande_le = null, recu_le = null where id = p_id;
  else
    raise exception 'Action inconnue : %', p_action;
  end if;
  select * into d from labo_demandes where id = nouvel_id;
  return d;
end $$;

-- Emplacements : tous les profs en créent ; modifier un existant = administratrice.
create or replace function labo_lieu_enregistrer(p_code text, p_id text, p_salle text, p_nom text,
                                                 p_details text default null, p_ordre int default 0)
returns labo_lieux
language plpgsql security definer set search_path = public as $$
declare l labo_lieux;
begin
  perform labo_exiger(p_code, exists (select 1 from labo_lieux where id = p_id));
  insert into labo_lieux(id, salle, nom, details, ordre)
       values (p_id, p_salle, p_nom, p_details, p_ordre)
  on conflict (id) do update
     set salle = excluded.salle, nom = excluded.nom, details = excluded.details, ordre = excluded.ordre;
  select * into l from labo_lieux where id = p_id;
  return l;
end $$;

